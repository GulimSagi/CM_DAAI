#Commit (сохранить изменения в историю):
#Измени что-нибудь в коде и сохрани файл.
#Нажми ⌘ + K. Откроется окно коммита.
#Отметь файлы, которые нужно включить.
#Напиши короткое сообщение, что ты сделала (например, Добавила функцию подсчёта).
#Нажми Commit. Если хочешь сразу отправить на GitHub, нажми стрелку рядом и выбери Commit and Push.
#Push (отправить коммиты на GitHub):
#Нажми ⌘ + Shift + K.
#В окне видно, какие коммиты уйдут. Нажми Push.
#Обнови страницу репозитория на GitHub, там появятся твои изменения.
#Pull (забрать изменения с GitHub):
#Выбери Git → Pull.
#Нажми Pull в открывшемся окне.
#Pull нужен, если ты меняла что-то на другом компьютере или прямо на сайте GitHub. Если работаешь только на этом Маке, он тебе почти не понадобится.
#Обычный порядок
#Поменяла код → ⌘ + K (Commit) → ⌘ + Shift + K (Push). Это основной цикл.
